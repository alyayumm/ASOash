export default function LegalPage({ kind }: { kind: 'privacy' | 'consent' }) {
  const title = kind === 'privacy' ? 'Политика конфиденциальности' : 'Согласие на обработку персональных данных'
  useEffect(() => {
    const previousTitle = document.title
    document.title = `${title} | АСО Автошкол`
    window.scrollTo(0, 0)
    return () => { document.title = previousTitle }
  }, [title])
  return <div className="legal-page">
    <header className="system-page-header"><div className="content-shell system-page-header__shell">
      <a className="header-logo-link" href="./" aria-label="АСО Автошкол — на главную"><BrandLogo /></a>
      <a className="legal-back" href="./?page=employers">К программе для работодателей</a>
    </div></header>
    <main className="system-page" id="top">
      <section className="system-page-hero"><div className="content-shell system-page-hero__layout">
        <p className="brand-kicker">Правовая информация · {LEGAL_DATE}</p><h1>{title}</h1>
        <p>{kind === 'privacy' ? 'Как мы работаем с данными, которые вы передаёте через сайт.' : 'Условия обработки данных при отправке заявки через сайт.'}</p>
        <LegalLinks />
      </div></section>
      <div className="system-page-content"><div className="content-shell legal-document">{kind === 'privacy' ? <Privacy /> : <Consent />}</div></div>
    </main>
  </div>
}
